// Regenerate the standalone study module from the shared implementation.
const fs = require('node:fs');
const ts = require('typescript');
let source = fs.readFileSync('src/components/brand/lettering-morph.ts', 'utf8')
  .replace('import glyphs from "./lettering-morph.json";', `const glyphs = ${fs.readFileSync('src/components/brand/lettering-morph.json', 'utf8')};`);
source += `
window.initLetteringMorph=()=>{
  window.strelvaMorph?.destroy();
  window.strelvaMorph=createLetteringMorph(document.querySelector('.wordmark .lockup'));
  window.strelvaMorph.set(document.querySelector('#logo-switch').dataset.new==='true');
};
window.initLetteringMorph();`;
fs.writeFileSync('docs/prototypes/atmospheric-launch/lettering-morph.js',
  '// Generated by scripts/design/build-lettering-morph.cjs.\n' +
  ts.transpileModule(source, {compilerOptions:{target:ts.ScriptTarget.ES2020,module:ts.ModuleKind.ES2020}}).outputText);
// Preserve a readable initial wordmark before JavaScript loads.
const glyphs = JSON.parse(fs.readFileSync('src/components/brand/lettering-morph.json', 'utf8'));
const htmlPath = 'docs/prototypes/atmospheric-launch/reference-material.html';
let html = fs.readFileSync(htmlPath, 'utf8');
glyphs.forEach((contours, index) => {
  const d = contours.map(contour => contour.from.map((point, i) =>
    `${i ? 'L' : 'M'}${point[0].toFixed(2)},${point[1].toFixed(2)}`).join('') + 'Z').join('');
  html = html.replace(new RegExp(`<path data-morph-letter="${index}"[^>]*/>`),
    `<path data-morph-letter="${index}" fill-rule="evenodd" d="${d}"/>`);
});
fs.writeFileSync(htmlPath, html);
